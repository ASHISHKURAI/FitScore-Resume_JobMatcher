import pdfplumber
from sentence_transformers import SentenceTransformer
from sklearn.metrics.pairwise import cosine_similarity
from groq import Groq
import os
import json
from datetime import datetime
from dotenv import load_dotenv
from fpdf import FPDF

load_dotenv()

model = SentenceTransformer('all-MiniLM-L6-v2')

client = Groq(api_key=os.getenv("GROQ_API_KEY"))


def extract_resume_text(uploaded_file):
    text = ""
    with pdfplumber.open(uploaded_file) as pdf:
        for page in pdf.pages:
            page_text = page.extract_text()
            if page_text:
                text += page_text + "\n"
    return text.strip()


def get_match_score(resume_text, jd_text):
    embeddings = model.encode([resume_text, jd_text])
    score = cosine_similarity([embeddings[0]], [embeddings[1]])[0][0]
    return round(float(score) * 100, 2)


def get_skill_gaps(resume_text, jd_text):
    prompt = f"""Compare this resume against this job description carefully.

RESUME:
{resume_text[:3000]}

JOB DESCRIPTION:
{jd_text[:3000]}

Return ONLY valid JSON (no markdown, no preamble, no explanation) in this exact structure:
{{
  "matching_skills": ["skill1", "skill2"],
  "missing_skills": ["skill1", "skill2"],
  "suggestions": ["specific actionable suggestion 1", "specific actionable suggestion 2"]
}}"""

    response = client.chat.completions.create(
        model=os.getenv("GROQ_MODEL", "openai/gpt-oss-120b"),
        max_tokens=2000,
        temperature=0.3,
        response_format={"type": "json_object"},
        messages=[{"role": "user", "content": prompt}]
    )

    raw_text = response.choices[0].message.content.strip()
    gaps = json.loads(raw_text)
    for key in ("matching_skills", "missing_skills", "suggestions"):
        gaps.setdefault(key, [])
    return gaps


def get_verdict(score):
    """Returns (tone, label, message) for a match score."""
    if score >= 75:
        return "good", "Strong match", "You're well-aligned with this role."
    if score >= 50:
        return "ok", "Decent match", "A few tweaks could strengthen your application."
    return "low", "Low match", "Consider whether this role fits your current skillset, or update your resume."


def get_skill_coverage(gaps):
    """Percentage of the JD's identified skills that the resume already covers."""
    matching = len(gaps.get("matching_skills", []))
    total = matching + len(gaps.get("missing_skills", []))
    return round(matching / total * 100) if total else 0


# ---------- PDF report ----------

BRAND = (79, 70, 229)
TONE_COLORS = {"good": (22, 163, 74), "ok": (217, 119, 6), "low": (220, 38, 38)}

_UNICODE_TO_ASCII = str.maketrans({
    "‘": "'", "’": "'", "“": '"', "”": '"',
    "–": "-", "—": "-", "•": "-", "…": "...", " ": " ",
})


def _pdf_safe(text):
    # Core PDF fonts only support latin-1
    text = str(text).translate(_UNICODE_TO_ASCII)
    return text.encode("latin-1", "replace").decode("latin-1")


class _Report(FPDF):
    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f"Generated by FitScore  |  Page {self.page_no()}/{{nb}}", align="C")


def _section_heading(pdf, title, color):
    if pdf.get_y() > pdf.page_break_trigger - 25:
        pdf.add_page()
    pdf.ln(5)
    y = pdf.get_y()
    pdf.set_fill_color(*color)
    pdf.rect(pdf.l_margin, y + 1, 1.5, 7, style="F")
    pdf.set_x(pdf.l_margin + 4)
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(30, 30, 30)
    pdf.cell(0, 9, title, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1)


def _item_list(pdf, items, numbered=False):
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(55, 55, 55)
    for i, item in enumerate(items or ["None identified"], 1):
        pdf.set_x(pdf.l_margin + 4)
        pdf.cell(7, 6.5, f"{i}." if numbered else "-")
        pdf.multi_cell(0, 6.5, _pdf_safe(item), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1)


def create_pdf_report(score, gaps, resume_name=None, jd_text=None, generated_at=None):
    generated_at = generated_at or datetime.now()
    tone, label, message = get_verdict(score)
    tone_color = TONE_COLORS[tone]
    matching = gaps.get("matching_skills", [])
    missing = gaps.get("missing_skills", [])

    pdf = _Report()
    pdf.set_auto_page_break(True, margin=20)
    pdf.add_page()
    left = pdf.l_margin

    # Header band
    pdf.set_fill_color(*BRAND)
    pdf.rect(0, 0, pdf.w, 34, style="F")
    pdf.set_xy(left, 8)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 22)
    pdf.cell(0, 10, "FitScore Report", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(224, 231, 255)
    pdf.cell(0, 6, "Resume vs. job description analysis", new_x="LMARGIN", new_y="NEXT")

    # Report details
    pdf.set_y(42)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 100, 100)
    if resume_name:
        pdf.cell(0, 6, _pdf_safe(f"Resume: {resume_name}"), new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, f"Generated: {generated_at:%d %b %Y, %I:%M %p}", new_x="LMARGIN", new_y="NEXT")

    # Score box with progress bar
    pdf.ln(4)
    y = pdf.get_y()
    pdf.set_fill_color(245, 246, 255)
    pdf.set_draw_color(224, 227, 255)
    pdf.rect(left, y, pdf.epw, 36, style="DF", round_corners=True)
    pdf.set_xy(left + 6, y + 5)
    pdf.set_font("Helvetica", "B", 30)
    pdf.set_text_color(*tone_color)
    pdf.cell(55, 16, f"{score}%")
    pdf.set_xy(left + 64, y + 6)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 30, 30)
    pdf.cell(0, 7, label)
    pdf.set_xy(left + 64, y + 14)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(90, 90, 90)
    pdf.multi_cell(pdf.epw - 70, 5, message)
    bar_width = pdf.epw - 12
    pdf.set_fill_color(225, 225, 235)
    pdf.rect(left + 6, y + 27, bar_width, 3, style="F")
    pdf.set_fill_color(*tone_color)
    pdf.rect(left + 6, y + 27, bar_width * max(0, min(score, 100)) / 100, 3, style="F")

    # Stat boxes
    y += 42
    gap = 4
    box_width = (pdf.epw - 2 * gap) / 3
    stats = [
        (str(len(matching)), "Matching skills", (22, 163, 74)),
        (str(len(missing)), "Missing skills", (220, 38, 38)),
        (f"{get_skill_coverage(gaps)}%", "Skill coverage", BRAND),
    ]
    pdf.set_fill_color(250, 250, 252)
    pdf.set_draw_color(230, 230, 238)
    for i, (value, stat_label, color) in enumerate(stats):
        x = left + i * (box_width + gap)
        pdf.rect(x, y, box_width, 20, style="DF", round_corners=True)
        pdf.set_xy(x, y + 3)
        pdf.set_font("Helvetica", "B", 15)
        pdf.set_text_color(*color)
        pdf.cell(box_width, 8, value, align="C")
        pdf.set_xy(x, y + 11)
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(110, 110, 110)
        pdf.cell(box_width, 5, stat_label, align="C")
    pdf.set_y(y + 22)

    _section_heading(pdf, "Matching Skills", (22, 163, 74))
    _item_list(pdf, matching)
    _section_heading(pdf, "Missing Skills", (220, 38, 38))
    _item_list(pdf, missing)
    _section_heading(pdf, "Suggestions to Improve Your Match", BRAND)
    _item_list(pdf, gaps.get("suggestions", []), numbered=True)

    if jd_text:
        _section_heading(pdf, "Job Description (for reference)", (120, 120, 140))
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(90, 90, 90)
        excerpt = jd_text.strip()
        if len(excerpt) > 6000:
            excerpt = excerpt[:6000] + "\n[...truncated]"
        pdf.multi_cell(0, 5, _pdf_safe(excerpt), new_x="LMARGIN", new_y="NEXT")

    return bytes(pdf.output())


